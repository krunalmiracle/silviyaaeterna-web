#!/usr/bin/env python3
"""Integrate verified originals; generate a mobile derivative and social card.
Run only after all independent asset-producer outputs exist:
uv run --with pillow python tools/prepare_images.py /opt/data/home/silviya-glasshouse-assets
This tool writes only this worktree; it never edits producer originals.
"""
from pathlib import Path
from PIL import Image, ImageOps, ImageDraw, ImageFont, PngImagePlugin
import hashlib
import json
import shutil
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCE = Path(sys.argv[1]) if len(sys.argv)>1 else Path('/opt/data/home/silviya-glasshouse-assets')
NAMES = ['hero-glasshouse.webp','sky-study.webp','skin-ritual.webp','quiet-growth.webp']
required = [SOURCE / n for n in [*NAMES, 'ASSET-MANIFEST.json', 'SUMMARY.md']]
missing = [str(p) for p in required if not p.is_file()]
if missing:
    raise SystemExit('PENDING ORIGINAL INPUT (nothing copied):\n'+'\n'.join(missing))
manifest = json.loads((SOURCE/'ASSET-MANIFEST.json').read_text())
assert manifest['asset_count'] == len(NAMES)
entries = {entry['filename']: entry for entry in manifest['assets']}
SCRIPTS = ['render.py', 'export_scenes.py', 'render_mitsuba.py', 'package_assets.py',
           'verify_assets.py', 'reproduce.sh', 'dependencies.txt', 'ORIGIN.md']
for name in SCRIPTS:
    assert (SOURCE/'source'/name).is_file(), f'Missing reproducible source: {name}'
# The independent producer manifest remains intact, never reinterpreted as image-model provenance.
OUT = ROOT/'assets/images'
OUT.mkdir(parents=True, exist_ok=True)
records = []
for name in NAMES:
    source = SOURCE/name
    with Image.open(source) as img:
        img.load()
        assert img.format=='WEBP', f'{name} is not a WebP'
        assert min(img.size)>=700, f'{name} is unexpectedly small'
        width,height=img.size
        assert (width,height) == (entries[name]['width'],entries[name]['height'])
        assert img.info.get('xmp'), f'Missing embedded provenance: {name}'
    assert source.stat().st_size == entries[name]['bytes']
    assert hashlib.sha256(source.read_bytes()).hexdigest() == entries[name]['sha256']
    shutil.copy2(source,OUT/name)
    records.append({'path':f'assets/images/{name}','width':width,'height':height,'bytes':source.stat().st_size,'sha256':hashlib.sha256(source.read_bytes()).hexdigest(),'origin':'Independent original render; see ASSET-MANIFEST.json'})
shutil.copy2(SOURCE/'ASSET-MANIFEST.json',ROOT/'tools/ASSET-MANIFEST.json')
shutil.copy2(SOURCE/'SUMMARY.md',ROOT/'tools/ASSET-SUMMARY.md')
# Preserve the producer's asset-root/source layout; no caches, meshes or .blend binaries.
for name in SCRIPTS:
    path=SOURCE/'source'/name
    dest=ROOT/'tools/glasshouse-source/source'/name
    dest.parent.mkdir(parents=True,exist_ok=True)
    shutil.copy2(path,dest)
for name in NAMES:
    shutil.copy2(SOURCE/(name+'.json'),ROOT/'tools/glasshouse-source'/(name+'.json'))
shutil.copy2(SOURCE/'SUMMARY.md',ROOT/'tools/glasshouse-source/SUMMARY.md')
hero=Image.open(OUT/'hero-glasshouse.webp')
mobile=ImageOps.contain(hero,(780,780),Image.Resampling.LANCZOS)
origin='Responsive derivative of original locally rendered hero-glasshouse.webp. No image-generation model or stock source. Source: tools/ASSET-MANIFEST.json.'
xmp=('<?xpacket begin=""?><x:xmpmeta xmlns:x="adobe:ns:meta/"><rdf:RDF xmlns:rdf="http://www.w3.org/1999/02/22-rdf-syntax-ns#"><rdf:Description xmlns:dc="http://purl.org/dc/elements/1.1/"><dc:description>'+origin+'</dc:description></rdf:Description></rdf:RDF></x:xmpmeta><?xpacket end="w"?>').encode()
mobile.save(OUT/'hero-glasshouse-mobile.webp',quality=86,method=6,xmp=xmp)
records.append({'path':'assets/images/hero-glasshouse-mobile.webp','width':mobile.width,'height':mobile.height,'bytes':(OUT/'hero-glasshouse-mobile.webp').stat().st_size,'origin':origin})
# Real social preview, using the delivered still life and brand lettering, not an old diagram.
card=Image.new('RGB',(1200,630),'#e6ede3')
art=ImageOps.fit(hero.convert('RGB'),(670,630),Image.Resampling.LANCZOS,centering=(.58,.5))
card.paste(art,(530,0))
draw=ImageDraw.Draw(card)
fontpath=str(ROOT/'tools/Onest-source.ttf')
font=ImageFont.truetype(fontpath,70)
small=ImageFont.truetype(fontpath,23)
body=ImageFont.truetype(fontpath,32)
draw.text((48,68),'Silviya',font=font,fill='#183f35')
draw.text((48,145),'Aeterna',font=font,fill='#183f35')
draw.text((48,342),'A little more',font=body,fill='#183f35')
draw.text((48,386),'in tune.',font=body,fill='#183f35')
draw.text((48,538),'English / Български',font=small,fill='#466255')
metadata=PngImagePlugin.PngInfo()
metadata.add_text('Title','Silviya Aeterna | A little more in tune')
metadata.add_text('Source','Original composite of hero-glasshouse.webp (see tools/ASSET-MANIFEST.json) and locally rendered Onest lettering, SIL OFL 1.1.')
metadata.add_text('Description','Original rendered illustration, not a photograph of a real place or a product endorsement. Generated by tools/prepare_images.py with Pillow.')
card.save(ROOT/'assets/social-og.png',pnginfo=metadata,optimize=True)
records.append({'path':'assets/social-og.png','width':1200,'height':630,'bytes':(ROOT/'assets/social-og.png').stat().st_size,'origin':'Pillow composite of original hero render and Onest brand text; tools/prepare_images.py'})
(ROOT/'tools/INTEGRATED-ASSETS.json').write_text(json.dumps(records,indent=2)+'\n')
print(json.dumps(records,indent=2))
